CREATE FUNCTION app.reject_approved_agent_name_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $
BEGIN
  RAISE EXCEPTION 'approved agent name catalog is immutable';
END
$;

CREATE TRIGGER approved_agent_names_immutable
BEFORE INSERT OR UPDATE OR DELETE ON app.approved_agent_names
FOR EACH STATEMENT EXECUTE FUNCTION app.reject_approved_agent_name_mutation();

CREATE TABLE app.agent_identities (
  id app.entity_id PRIMARY KEY DEFAULT app.new_id(),
  organization_id app.entity_id NOT NULL REFERENCES app.organizations(id) ON DELETE CASCADE,
  approved_name_id smallint NOT NULL REFERENCES app.approved_agent_names(id),
  display_name text NOT NULL CHECK (display_name = btrim(display_name) AND length(display_name) BETWEEN 1 AND 120),
  status text NOT NULL DEFAULT 'inactive' CHECK (status IN ('inactive', 'active', 'archived')),
  version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by_membership_id app.entity_id NOT NULL,
  created_at timestamptz NOT NULL DEFAULT app.utc_now(),
  updated_at timestamptz NOT NULL DEFAULT app.utc_now(),
  UNIQUE (organization_id, id),
  UNIQUE (organization_id, approved_name_id),
  FOREIGN KEY (organization_id, updated_by_membership_id)
    REFERENCES app.memberships(organization_id, id)
);

ALTER TABLE app.agent_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.agent_identities FORCE ROW LEVEL SECURITY;
CREATE POLICY agent_identities_tenant_isolation ON app.agent_identities
  USING (organization_id = app.current_organization_id())
  WITH CHECK (organization_id = app.current_organization_id());
